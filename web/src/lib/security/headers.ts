// Relative imports: next.config.ts loads this file, outside the `@/` alias.
import { EMBED_FRAME_SOURCES } from "../../features/blocks/embeds";
import { HANDLE_PATTERN, RESERVED_HANDLES } from "../../features/profiles/handle";

/**
 * HTTP security headers applied to every route via next.config.ts `headers()`.
 * Pure data so it can be unit-tested and asserted against production responses.
 * Policy rationale and its known weaknesses: SECURITY.md (Security headers).
 *
 * Why `'unsafe-inline'` remains in script-src/style-src: Next.js streams its
 * RSC payload and bootstrap code as inline <script> tags, and Partial
 * Prerendering (on via Cache Components) serves those from a static
 * shell where a per-request nonce cannot be injected. Next.js documents nonce
 * CSP as incompatible with PPR, and SRI hashes only cover external files.
 */
export function contentSecurityPolicy({ isDev, frameSources = ["'none'"] }: { isDev: boolean; frameSources?: readonly string[] }): string {
  const directives: Record<string, readonly string[]> = {
    "default-src": ["'self'"],
    // 'unsafe-eval' only for React's development tooling.
    "script-src": ["'self'", "'unsafe-inline'", ...(isDev ? ["'unsafe-eval'"] : [])],
    "style-src": ["'self'", "'unsafe-inline'"],
    // https: lets profile owners use externally hosted avatars. Visitors'
    // browsers then contact owner-chosen hosts (IP and user agent are exposed).
    "img-src": ["'self'", "data:", "blob:", "https:"],
    "font-src": ["'self'"],
    "connect-src": ["'self'"],
    "frame-src": frameSources,
    "frame-ancestors": ["'none'"],
    "object-src": ["'none'"],
    "base-uri": ["'self'"],
    "form-action": ["'self'"],
    "manifest-src": ["'self'"],
    "worker-src": ["'self'", "blob:"],
  };
  return Object.entries(directives)
    .map(([name, values]) => `${name} ${values.join(" ")}`)
    .join("; ");
}

/**
 * Headers for uploaded media under `/media/`, set by the media route
 * itself and, for the same paths, by next.config.ts instead of the page
 * headers. The files are re-encoded WebP images: no script can run (sandboxed,
 * `default-src 'none'`), they are never type-sniffed, other sites can't embed
 * them (CORP), and they aren't indexed.
 */
export const MEDIA_CSP = "sandbox; default-src 'none'";

export function mediaResponseHeaders(): Record<string, string> {
  return {
    "content-security-policy": MEDIA_CSP,
    "x-content-type-options": "nosniff",
    "cross-origin-resource-policy": "same-origin",
    "x-robots-tag": "noindex",
    "referrer-policy": "no-referrer",
    "x-frame-options": "DENY",
  };
}

/**
 * Headers for the owner's QR-code download (`/dashboard/profiles/{id}/qr`),
 * set by the route and excluded from the page headers in
 * next.config.ts so there is exactly one CSP. The SVG is generated by the
 * server from the profile URL; it is still served sandboxed, never sniffed,
 * as an attachment and uncached.
 */
export function qrResponseHeaders(fileName: string): Record<string, string> {
  return {
    ...mediaResponseHeaders(),
    "content-type": "image/svg+xml; charset=utf-8",
    "content-disposition": `attachment; filename="${fileName}"`,
    "cache-control": "private, no-store",
  };
}

/**
 * RFC 5987 `value-chars` for `filename*`: UTF-8 percent-encoded; `'()*` are
 * encoded too because they aren't `attr-char`s.
 */
function rfc5987(value: string): string {
  return encodeURIComponent(value).replace(/['()*]/g, (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`);
}

/**
 * The contact-card download's security headers: sandboxed and
 * never sniffed like media, uncached (unpublishing, hiding or editing applies
 * at once) and not indexed. next.config.ts sets them for exactly
 * `VCARD_HEADERS_SOURCE`, instead of the page headers, so the responses Next.js
 * itself generates on that path (a 400 for a non-HTTP method) are covered too;
 * the route sets the same fields on its own responses, which replace these
 * values rather than adding a second copy.
 */
export function vcardSecurityHeaders(): Record<string, string> {
  return {
    ...mediaResponseHeaders(),
    "cache-control": "no-store",
    "x-robots-tag": "noindex, nofollow",
  };
}

/**
 * Headers for every response of the public contact-card download
 * (`/api/vcard/{profileId}/{blockId}`: 200, HEAD, 404 and 405), set by the
 * route. `fileNames` is given only for the card itself: an ASCII fallback
 * (`[A-Za-z0-9._-]`) and an optional UTF-8 name sent as RFC 6266 `filename*`.
 */
export function vcardResponseHeaders(fileNames?: { ascii: string; utf8?: string }): Record<string, string> {
  const base = vcardSecurityHeaders();
  if (!fileNames) return { ...base, "content-type": "text/plain; charset=utf-8" };
  const disposition = `attachment; filename="${fileNames.ascii}"${fileNames.utf8 ? `; filename*=UTF-8''${rfc5987(fileNames.utf8)}` : ""}`;
  return { ...base, "content-type": "text/vcard; charset=utf-8", "content-disposition": disposition };
}

/**
 * next.config.ts path pattern for the contact-card download: exactly two
 * segments after `/api/vcard/`. `PAGE_HEADERS_SOURCE` excludes
 * exactly the same paths, so every path gets one of the two header sets.
 */
export const VCARD_HEADERS_SOURCE = "/api/vcard/:profileId/:blockId";

/**
 * One path segment of the handle shape that the app doesn't own: a public
 * profile, or a 404 that renders no iframe (`next.config` headers can't see
 * whether a handle is live). A reserved name with a dot can't take the shape.
 */
const RESERVED_ALTERNATIVES = [...RESERVED_HANDLES].filter((h) => HANDLE_PATTERN.test(h)).join("|");
const PROFILE_PATH = `(?!(?:${RESERVED_ALTERNATIVES})$)${HANDLE_PATTERN.source.slice(1, -1)}`;

/**
 * next.config.ts path pattern for public profile pages, the only
 * routes with the embed `frame-src`. `PAGE_HEADERS_SOURCE` excludes exactly the
 * same paths, so each response has one CSP. The route inventory test requires
 * every top-level route of the app to be reserved.
 */
export const PROFILE_HEADERS_SOURCE = `/:handle(${PROFILE_PATH})`;

/**
 * next.config.ts path pattern for every route that gets the page headers: all
 * but media, the QR download, the token pages, the exact vCard route
 * (`/api/vcard`, one segment or three get the page headers) and the
 * public profile pages.
 */
export const PAGE_HEADERS_SOURCE = `/:path((?!media/|dashboard/profiles/[^/]+/qr$|reset-password$|verify-email$|api/vcard/[^/]+/[^/]+$|${PROFILE_PATH}$).*)`;

/** next.config.ts path pattern for the pages that receive a token in their link fragment. */
export const TOKEN_PAGE_HEADERS_SOURCE = "/:page(reset-password|verify-email)";

export function securityHeaders({ isDev }: { isDev: boolean }): { key: string; value: string }[] {
  return [
    { key: "Content-Security-Policy", value: contentSecurityPolicy({ isDev }) },
    { key: "X-Content-Type-Options", value: "nosniff" },
    { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
    { key: "X-Frame-Options", value: "DENY" },
    { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
    {
      key: "Permissions-Policy",
      value: "camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()",
    },
  ];
}

/**
 * The page headers with the only `frame-src` that allows anything: the
 * four provider players. A CSP belongs to the document, so this works because
 * public pages are reached only by full-page links; the dashboard keeps
 * `frame-src 'none'` and its preview renders no iframe.
 */
export function profileSecurityHeaders({ isDev }: { isDev: boolean }): { key: string; value: string }[] {
  return securityHeaders({ isDev }).map((h) =>
    h.key === "Content-Security-Policy" ? { key: h.key, value: contentSecurityPolicy({ isDev, frameSources: EMBED_FRAME_SOURCES }) } : h,
  );
}

/**
 * Headers for the pages that receive a reset or verification token in their
 * link fragment (`/reset-password`, `/verify-email`). They replace
 * the page headers there (excluded from `PAGE_HEADERS_SOURCE`), so each
 * field appears exactly once: the page headers with `Referrer-Policy:
 * no-referrer`, plus `no-store` and `noindex`. Next.js also marks these
 * dynamic pages uncacheable itself.
 */
export function tokenPageHeaders({ isDev }: { isDev: boolean }): { key: string; value: string }[] {
  return [
    ...securityHeaders({ isDev }).map((h) => (h.key === "Referrer-Policy" ? { key: h.key, value: "no-referrer" } : h)),
    { key: "Cache-Control", value: "no-store" },
    { key: "X-Robots-Tag", value: "noindex" },
  ];
}
